#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

# fmt wraps long declarations/calls and orders imports. Spacing is supplied by
# an analyzer, so fmt alone cannot apply the wsl_v5 fixes.
./scripts/golangci.sh fmt ./cmd/... ./internal/...
./scripts/golangci.sh run --enable-only wsl_v5 --fix ./cmd/... ./internal/...
./scripts/golangci.sh fmt ./cmd/... ./internal/...

# The same non-mutating check used by local/CI validation must accept the result.
./scripts/golangci.sh run ./cmd/... ./internal/...
